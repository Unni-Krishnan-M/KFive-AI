#!/usr/bin/env python3
"""Hash a reviewed, complete CPython 3.12/Linux amd64 wheel set without installing it."""

import argparse
import email.parser
import hashlib
import re
import zipfile
from pathlib import Path


def normalized(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def lock_wheels(directory, direct_requirements):
    packages = {}
    for wheel in sorted(directory.glob("*.whl")):
        if wheel.is_symlink() or not wheel.is_file():
            raise ValueError("Wheel must be a regular file")
        with zipfile.ZipFile(wheel) as archive:
            metadata = [item for item in archive.infolist() if item.filename.endswith(".dist-info/METADATA")]
            if len(metadata) != 1 or metadata[0].file_size > 1024 * 1024:
                raise ValueError("Wheel metadata is missing, ambiguous, or too large")
            parsed = email.parser.BytesParser().parsebytes(archive.read(metadata[0]), headersonly=True)
        name, version = parsed["Name"], parsed["Version"]
        if not name or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", name):
            raise ValueError("Invalid package name")
        if not version or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.!+_-]*", version):
            raise ValueError("Invalid package version")
        name = normalized(name)
        if name in packages:
            raise ValueError("Duplicate distribution in wheel set")
        with wheel.open("rb") as source:
            digest = hashlib.file_digest(source, "sha256").hexdigest()
        packages[name] = (version, digest)
    if not packages:
        raise ValueError("No wheels found")
    for line in direct_requirements.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"([A-Za-z0-9_.-]+)==([A-Za-z0-9.!+_-]+)", line)
        if not match or packages.get(normalized(match[1]), (None,))[0] != match[2]:
            raise ValueError("Direct requirement missing or differs from reviewed wheel set")
    header = (
        "# CPython 3.12 / Linux amd64 (Debian bookworm) reviewed wheel lock.\n"
        "# Captured from the previously tested runtime; no package-version upgrades.\n"
        "# Generated by scripts/lock-notebook-wheels.py; see docs/NOTEBOOKS.md.\n"
        "# Each hash covers one selected wheel. Other targets require separate locks.\n"
    )
    return header + "".join(
        f"{name}=={version} --hash=sha256:{digest}\n"
        for name, (version, digest) in sorted(packages.items())
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("wheel_directory", type=Path)
    parser.add_argument("--requirements", type=Path, default=Path("services/notebook-runtime/requirements.in"))
    parser.add_argument("--output", type=Path, default=Path("services/notebook-runtime/requirements.lock"))
    args = parser.parse_args()
    args.output.write_text(lock_wheels(args.wheel_directory, args.requirements))
